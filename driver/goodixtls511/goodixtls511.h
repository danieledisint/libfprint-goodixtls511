/* Frame geometry: 80 rows with a stride of 88 12-bit pixels, of which the
 * first 64 columns carry data. The decrypted frame has 8 header bytes and 5
 * trailing bytes around the packed pixels (6 bytes per 4 pixels). */
#define GOODIX_WIDTH 64
#define GOODIX_HEIGHT 80
#define GOODIX_STRIDE 88
#define GOODIX_FRAME_HEADER 8
#define GOODIX_FRAME_TRAILER 5
#define GOODIX_FRAME_SIZE \
  (GOODIX_FRAME_HEADER + GOODIX_HEIGHT * GOODIX_STRIDE / 4 * 6 + GOODIX_FRAME_TRAILER)

